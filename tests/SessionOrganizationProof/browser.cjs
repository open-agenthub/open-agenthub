const { chromium } = require(process.env.PLAYWRIGHT_PATH || '/opt/session-agent/node_modules/playwright-core')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.connectOverCDP(process.env.CDP_ENDPOINT)
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage(); const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(process.env.PROOF_URL || 'http://10.42.1.4:5173')
  await page.locator('[data-session-row="order-a"]').waitFor()
  async function api(path, method = 'GET', body) {
    return page.evaluate(async ({path, method, body}) => {
      const r = await fetch('/api/' + path, { method, headers: {'Content-Type':'application/json'}, body: body ? JSON.stringify(body) : undefined })
      return { status: r.status, body: r.status === 204 ? null : await r.json().catch(() => null) }
    }, {path,method,body})
  }
  await api('session-organization/order-a/project', 'POST', {projectId:null,confirm:true})
  assert.equal((await api('session-organization/order', 'PUT', {sessionIds:['order-a','order-b','order-c']})).status, 204)
  await page.reload(); await page.locator('[data-session-row="order-a"]').waitFor()
  const response = page.waitForResponse(r => r.url().endsWith('/session-organization/order') && r.request().method() === 'PUT')
  await page.locator('[data-session-row="order-c"]').dragTo(page.locator('[data-session-row="order-a"]'))
  assert.equal((await response).status(), 204)
  await page.reload(); await page.locator('[data-session-row="order-a"]').waitFor()
  assert.deepEqual((await api('session-organization/order')).body.slice(0,3), ['order-c','order-a','order-b'])
  const project = (await api('projects', 'POST', {name:'Destination '+Date.now(), color:null})).body
  await page.reload(); await page.locator('[data-session-row="order-a"]').waitFor()
  await page.locator('[data-session-row="order-a"]').dragTo(page.locator('[data-project-drop="'+project.id+'"]'))
  await page.getByRole('dialog').waitFor()
  assert.match(await page.locator('[data-project-move-impact]').textContent(), /Access to files in the old project ends/)
  assert.equal((await api('sessions/order-a')).body.projectId, null)
  await page.locator('[data-confirm-move]').click()
  await page.getByRole('dialog').waitFor({state:'hidden'})
  assert.equal((await api('sessions/order-a')).body.projectId, project.id)
  assert.equal((await api('session-organization/foreign-session/project','POST',{projectId:project.id,confirm:true})).status,404)
  assert.equal((await api('session-organization/order','PUT',{sessionIds:['foreign-session']})).status,404)
  // Native dialog/menu remains reachable by keyboard and by touch.
  await page.locator('[data-session-row="order-a"] [aria-label="Organize session"]').focus()
  await page.keyboard.press('Enter'); await page.getByRole('dialog').waitFor()
  await page.getByLabel('Move to project').selectOption('')
  await page.locator('[data-confirm-move]').click(); await page.getByRole('dialog').waitFor({state:'hidden'})
  assert.equal((await api('sessions/order-a')).body.projectId,null)
  await page.setViewportSize({width:390,height:844})
  const mobileMenu = page.getByRole('button', {name:/Open navigation/})
  if (await mobileMenu.count()) await mobileMenu.click()
  await page.locator('[data-session-row="order-a"]').click()
  await page.getByRole('button', {name:'Sessions', exact:true}).click()
  await page.locator('[data-session-row="order-a"] [aria-label="Organize session"]').click()
  await page.getByRole('dialog').waitFor()
  await page.getByLabel('Move to project').selectOption(project.id)
  await page.locator('[data-confirm-move]').click(); await page.getByRole('dialog').waitFor({state:'hidden'})
  assert.equal((await api('sessions/order-a')).body.projectId,project.id)
  assert.deepEqual(errors, [])
  console.log('PASS real Chromium: persisted drag reorder, project drag confirmation, 404 foreign session/order, keyboard move, mobile move; no page errors')
  await context.close(); await browser.close()
})().catch(e => {console.error(e);process.exit(1)})
