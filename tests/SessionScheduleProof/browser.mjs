// Drive the branch's real dialog against the real backend, then inspect cluster objects.
import fs from 'node:fs'
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { execFileSync } from 'node:child_process'
const require = createRequire(new URL('../../browser-runtime/package.json',import.meta.url))
const {chromium}=require('playwright-core')
const [fixtureFile,output]=process.argv.slice(2)
const fixtureLine=fs.readFileSync(fixtureFile,'utf8').split('\n').find(line=>line.startsWith('FIXTURE '))
assert.ok(fixtureLine,'HTTP proof must complete and emit its fixture')
const fixture=JSON.parse(fixtureLine.slice('FIXTURE '.length))
const k=(...args)=>JSON.parse(execFileSync(process.env.KUBECTL||'kubectl',['--kubeconfig',process.env.PROOF_KUBECONFIG,'-n','agenthub-sessions',...args,'-o','json'],{encoding:'utf8'}))
const before=k('get','job',fixture.job)
const podBefore=k('get','pod',fixture.pod)
const browser=await chromium.launch({executablePath:process.env.CHROMIUM,args:['--no-sandbox','--disable-dev-shm-usage']})
try {
  const page=await browser.newPage({viewport:{width:1440,height:1100}})
  page.setDefaultTimeout(15000)
  page.on('console',m=>{if(m.type()==='error')console.log('Browser console:',m.text())})
  console.log('Browser navigating')
  const errors=[];page.on('pageerror',e=>errors.push(String(e)))
  await page.goto(`http://127.0.0.1:5173/s/${fixture.sessionId}`)
  console.log('Browser loaded', await page.title())
  await page.screenshot({path:output})
  await page.getByRole('button',{name:/Edit session/}).click()
  await page.waitForSelector('[data-schedule]')
  assert.equal(await page.inputValue('[data-schedule]'),'0 11 * * *')
  assert.match(await page.textContent('[data-next-run]'),/Next run \(UTC\): \d{4}-\d{2}-\d{2}/)
  await page.fill('[data-schedule]','bad')
  await page.click('[data-submit]')
  await page.locator('.err').waitFor()
  assert.match(await page.textContent('.err'),/valid five-field UTC cron/)
  assert.equal(k('get','cronjob',`session-${fixture.sessionId}`).spec.schedule,'0 11 * * *')
  console.log('PASS real Chromium displays next run and keeps dialog open on invalid schedule')
  await page.fill('[data-schedule]','30 12 * * 1-5')
  const saved=page.waitForResponse(r=>r.request().method()==='PATCH' && r.url().endsWith(`/api/sessions/${fixture.sessionId}`))
  await page.click('[data-submit]');assert.equal((await saved).status(),200)
  await page.waitForSelector('[data-schedule]',{state:'hidden'})
  await page.getByRole('button',{name:/Edit session/}).click()
  assert.equal(await page.inputValue('[data-schedule]'),'30 12 * * 1-5')
  assert.match(await page.textContent('[data-next-run]'),/12:30:00/)
  await page.screenshot({path:output,fullPage:true})
  const cron=k('get','cronjob',`session-${fixture.sessionId}`)
  assert.equal(cron.metadata.uid,fixture.cronUid)
  assert.equal(cron.spec.schedule,'30 12 * * 1-5')
  assert.deepEqual(k('get','job',fixture.job),before)
  assert.deepEqual(k('get','pod',fixture.pod),podBefore)
  assert.deepEqual(errors,[])
  console.log('PASS real Chromium saves/reopens schedule with new next run; same CronJob UID and complete active Job preserved; no page errors')
} finally {await browser.close()}
