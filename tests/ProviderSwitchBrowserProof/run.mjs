import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire('/opt/session-agent/package.json');
const { chromium } = require('playwright-core');
assert(process.env.PROOF_CDP && process.env.PROOF_URL && process.env.PROOF_OUT);
fs.mkdirSync(process.env.PROOF_OUT, { recursive: true });
const browser = await chromium.connectOverCDP(process.env.PROOF_CDP);
const context = browser.contexts()[0];
const page = context.pages().find(item => item.url().replace(/\/$/, '') === process.env.PROOF_URL.replace(/\/$/, '')) || await context.newPage();
try {
 await page.setViewportSize({ width: 1280, height: 900 });
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(process.env.PROOF_URL);
 await page.getByRole('button',{name:'Switch provider',exact:true}).click();
 await page.getByText(/workspace uses emptyDir/).waitFor();
 assert.equal(await page.locator('form').count(),0);
 await page.getByRole('button',{name:'Close',exact:true}).click();
 await page.evaluate(()=>window.proof.enable());
 await page.getByRole('button',{name:'Switch provider',exact:true}).click();
 await page.getByLabel('Instructions to preserve').fill('Preserve the policy and dirty files.');
 await page.getByLabel('Task to continue').fill('Finish the feature.');
 await page.getByRole('button',{name:'Review exact handover'}).click();
 await page.locator('[data-provider-review] pre').waitFor();
 assert.match(await page.locator('[data-provider-review] pre').innerText(),/Omitted:/);
 await page.getByLabel('Task to continue').fill('Finish and verify the feature.');
 assert.equal(await page.locator('[data-provider-review]').count(),0);
 await page.getByRole('button',{name:'Review exact handover'}).click();
 await page.locator('[data-provider-review] pre').waitFor();
 await page.screenshot({path:path.join(process.env.PROOF_OUT,'review-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>{const box=document.querySelector('[data-provider-panel]').getBoundingClientRect();return document.documentElement.scrollWidth<=innerWidth&&box.left>=0&&box.right<=innerWidth}));
 await page.locator('[data-provider-review] pre').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(process.env.PROOF_OUT,'review-mobile.png')});
 await page.getByRole('button',{name:'Switch to Codex with this handover'}).click();
 await page.getByText('Switching to Codex: Waiting for a safe point.').waitFor();
 assert(await page.getByLabel('Composer').isDisabled());
 const sent=await page.evaluate(()=>window.proof.calls.find(item=>item.kind==='start').selection);
 assert.equal(sent.reviewHash,'review-hash');
 assert.match(sent.requestId,/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
 assert.equal(sent.handover.task,'Finish and verify the feature.');
 await page.getByRole('button',{name:'Cancel before source stop'}).click();
 await page.getByRole('heading',{name:'Continue with Codex'}).waitFor();
 await page.evaluate(()=>window.proof.failAfterStop());
 await page.getByText('Switching to Codex: Confirming the handover.').waitFor();
 assert.equal(await page.getByRole('button',{name:'Cancel before source stop'}).count(),0);
 await page.getByRole('button',{name:'Retry this replacement'}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('PASS: actual component in Chromium over HTTP; explicit emptyDir reason, exact reviewed text, edit invalidation, UUID, pending composer, cancellation boundary, retry, desktop/mobile layout.');
} finally { await page.close(); await browser.close(); }
