const { chromium } = require((process.env.PROOF_RUNTIME || '/opt/session-agent') + '/node_modules/playwright-core');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.connectOverCDP(process.argv[2]);
  const context = browser.contexts()[0];
  const page = await context.newPage();
  const errors = [], external = [], dialogs = [];
  page.on('dialog', async dialog => { dialogs.push(dialog.message()); await dialog.dismiss(); });
  await page.addInitScript(() => { localStorage.setItem('svg-proof', 'sentinel'); document.cookie = 'svg-proof=sentinel; path=/'; });
  page.on('pageerror', error => errors.push(String(error)));
  page.on('request', request => { if(request.url().includes('__svg-external')) external.push(request.url()); });
  await page.goto(process.argv[3] + '/s/s1');
  await page.getByRole('button', { name: 'Files', exact: true }).click();
  await page.getByText('probe.svg', {exact:true}).first().click();
  const image = page.locator('[data-file-preview="image"]');
  await image.waitFor();
  assert.match(await image.getAttribute('src'),/^data:image\/svg\+xml;base64,/);
  assert.equal(await image.evaluate(e => e.complete && e.naturalWidth > 0),true);
  assert.equal(await page.locator('.preview svg, .preview iframe, .preview object, .preview embed').count(),0);
  assert.equal(await page.evaluate(() => Boolean(window.svgExecuted)),false);
  assert.deepEqual(external,[]);
  assert.deepEqual(dialogs,[]);
  assert.equal(await page.evaluate(() => localStorage.getItem('svg-proof')),'sentinel');
  assert.match(await page.evaluate(() => document.cookie), /svg-proof=sentinel/);
  await page.getByText('probe.html', {exact:true}).first().click();
  await page.locator('[data-preview-unsupported]').waitFor();
  assert.equal(await page.locator('.preview iframe, .preview object, .preview embed').count(),0);
  assert.equal(await page.evaluate(() => Boolean(window.htmlExecuted)),false);
  assert.equal(await page.locator('.preview [data-file-download]').count(),1);
  console.log('PASS real Chromium Files pane: malicious SVG displays as img/data URL, no inline SVG, scripts or external request; HTML download-only');
  if(errors.length)console.log('Page errors:',errors);
  await page.close(); await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1});
