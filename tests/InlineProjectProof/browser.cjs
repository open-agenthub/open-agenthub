const { chromium } = require(process.env.PLAYWRIGHT_PATH || '/opt/session-agent/node_modules/playwright-core')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.connectOverCDP(process.env.CDP_ENDPOINT)
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto(process.env.PROOF_URL || 'http://10.42.1.4:5173')
  console.log((await page.locator('button').allTextContents()).slice(0,30))
  await page.getByRole('button', { name: /New session|Give an agent a task/ }).first().click()
  await page.getByLabel('Project', { exact: true }).selectOption('__new__')
  await page.getByLabel('Project name', { exact: true }).fill('Inline proof ' + Date.now())
  await page.locator('[data-mode-option]').filter({ hasText: 'Autonomous' }).click()
  await page.locator('[data-submit]').click()
  await page.getByRole('alert').filter({ hasText: 'A prompt is required' }).waitFor()
  assert.match(await page.locator('[data-project-notice]').textContent(), /stays saved/)
  const project = await page.getByLabel('Project', { exact: true }).inputValue()
  assert.notEqual(project, '__new__')
  await page.locator('[data-mode-option]').filter({ hasText: 'Interactive' }).click()
  const response = page.waitForResponse(r => r.url().endsWith('/api/sessions') && r.request().method() === 'POST')
  await page.locator('[data-submit]').click()
  const r = await response; console.log('session status', r.status(), await r.text())
  assert.equal(r.status(), 200)
  const session = await r.json(); assert.equal(session.projectId, project)
  const projects = await page.evaluate(() => fetch('/api/projects').then(r=>r.json()))
  assert.equal(projects.filter(p => p.id === project).length, 1)
  // Exercise the actual duplicate-name controller path from a second dialog.
  await page.goto(process.env.PROOF_URL || 'http://10.42.1.4:5173')
  await page.getByRole('button', { name: /New session|Give an agent a task/ }).first().click()
  await page.getByLabel('Project', { exact: true }).selectOption('__new__')
  await page.getByLabel('Project name', { exact: true }).fill(projects.find(p => p.id === project).name)
  await page.locator('[data-submit]').click()
  await page.getByRole('alert').filter({ hasText: 'A project with this name already exists.' }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS real Chromium: retained saved project after real 400, successful retry, real 409 duplicate; no page errors')
  await context.close(); await browser.close()
})().catch(e => { console.error(e); process.exit(1) })
