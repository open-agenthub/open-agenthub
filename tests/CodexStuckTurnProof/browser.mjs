// #562 browser proof: the branch web app (Vite) in real Chromium, attached through hub.mjs to
// the real Codex 0.167.0 in the real session agent, while the model's response hangs.
import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
const require = createRequire(process.env.RT + '/package.json')
const { chromium } = require('playwright-core')
const OUT = process.env.OUT
const executablePath = fs.readdirSync(path.join(process.env.HOME, '.cache/ms-playwright'))
  .filter(d => d.startsWith('chromium_headless_shell'))
  .map(d => path.join(process.env.HOME, '.cache/ms-playwright', d, 'chrome-headless-shell-linux64/chrome-headless-shell'))[0]
const t0 = Date.now()
const log = (...a) => console.log(`[${((Date.now() - t0) / 1000).toFixed(1)}s]`, ...a)
const browser = await chromium.launch({ executablePath, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const page = await browser.newPage({ viewport: { width: Number(process.env.WIDTH || 1440), height: 900 } })
page.on('pageerror', e => log('pageerror', e.message))
await page.addInitScript(() => localStorage.setItem('agenthub.preferredUi', 'workspace'))
await page.goto('http://localhost:5173/s/s1')
const composer = page.locator('[data-workspace-composer] textarea')
await composer.waitFor({ timeout: 60000 })
await page.waitForFunction(() => !document.querySelector('[data-workspace-composer] textarea')?.disabled, null, { timeout: 60000 })
const activityText = async () => (await page.locator('[data-workspace-activity]').allInnerTexts()).join(' | ')
await page.waitForSelector('[data-workspace-activity][data-state="working"]', { timeout: 60000 })
log('activity:', await activityText())
await composer.fill('MSG-B Please also check the README.')
await composer.press('Enter')
await page.waitForTimeout(3000)
log('after sending from the composer:', await activityText())
await page.screenshot({ path: path.join(OUT, 'browser-1-working.png') })
await page.waitForSelector('[data-stalled]', { timeout: Number(process.env.NOTICE_WAIT_MS || 120000) })
log('notice:', await activityText())
await page.screenshot({ path: path.join(OUT, 'browser-2-stalled.png') })
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(500)
const box = await page.locator('[data-stalled]').boundingBox()
log('phone 390: notice box', JSON.stringify(box), 'page scrollWidth', await page.evaluate(() => document.documentElement.scrollWidth))
await page.screenshot({ path: path.join(OUT, 'browser-3-stalled-phone.png') })
await page.setViewportSize({ width: 1440, height: 900 })
await page.waitForTimeout(500)
await page.click('[data-stalled-interrupt]')
log('clicked Interrupt')
await page.waitForFunction(() => !document.querySelector('[data-stalled]'), null, { timeout: 30000 })
await page.waitForTimeout(4000)
log('after interrupt:', await activityText() || '(no activity bar: idle)')
await page.screenshot({ path: path.join(OUT, 'browser-4-after-interrupt.png') })
await browser.close()
